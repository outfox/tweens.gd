// Deterministic helper catalog derived from the C# property adapters. No runtime dependency.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const snake = (name) =>
  name
    .replace(/([23])D([XYZ])/g, '$1d_$2')
    .replace(/([23])D/g, '$1d')
    .replace(/([a-zA-Z])([23]d)/g, '$1_$2')
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1_$2')
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .toLowerCase();
const types = {
  float: 'FLOAT',
  double: 'FLOAT',
  int: 'INT',
  Vector2: 'VECTOR2',
  Vector3: 'VECTOR3',
  Vector4: 'VECTOR4',
  Color: 'COLOR',
  Quaternion: 'QUATERNION',
  Rect2: 'RECT2',
};
const defaults = {
  float: '0.0',
  double: '0.0',
  Vector2: 'Vector2.ZERO',
  Vector3: 'Vector3.ZERO',
  Vector4: 'Vector4.ZERO',
  Color: 'Color(0, 0, 0, 0)',
  Quaternion: 'Quaternion.IDENTITY',
  Rect2: 'Rect2()',
};
const entries = [];
for (const file of fs
  .readdirSync(path.join(root, 'addons/tweens_gd/csharp/Tweens'))
  .filter((f) => f.endsWith('.cs'))
  .sort()) {
  const source = fs.readFileSync(path.join(root, 'addons/tweens_gd/csharp/Tweens', file), 'utf8');
  const matches = [
    ...source.matchAll(
      /public sealed class (\w+)Tween\(\) : PropertyTween<([\w.]+), (\w+)>\(\s*static [a-z_] => ([\s\S]*?), static \([\s\S]*?Interpolators\.(\w+)\)(?:;|\s*\{)/g,
    ),
  ];
  const expected = [...source.matchAll(/: PropertyTween</g)].length;
  if (matches.length !== expected)
    throw new Error(`Unrecognized adapter syntax in ${file}: ${matches.length}/${expected}`);
  for (const [, csharp, rawTarget, type, getter] of matches) {
    const target = rawTarget.replace('Godot.', '').replace(/^Gpu/, 'GPU').replace(/^Cpu/, 'CPU');
    const name = target === 'Node' ? `${snake(csharp)}_value` : snake(csharp);
    const entry = { csharp, name, target, type, kind: 'property', paths: [] };
    if (target === 'Node') entry.kind = 'value';
    else if (getter.startsWith('Quaternion.FromEuler')) entry.kind = 'global_quaternion';
    else if (getter.startsWith('new Vector')) {
      entry.kind = 'compound';
      entry.paths = [...getter.matchAll(/n\.(\w+)/g)].map((m) => snake(m[1]));
    } else if (/^[a-z]\.[\w.]+$/.test(getter))
      entry.paths = [getter.slice(2).split('.').map(snake).join(':')];
    else throw new Error(`Unsupported getter ${csharp}: ${getter}`);
    if (!types[type]) throw new Error(`Unsupported type ${type}`);
    entries.push(entry);
  }
}
entries.sort((a, b) => a.name.localeCompare(b.name, 'en'));
if (new Set(entries.map((e) => e.name)).size !== entries.length)
  throw new Error('Duplicate helper names');
let gd = `# SPDX-License-Identifier: MIT
# SPDX-FileCopyrightText: 2026 Moritz Voss
# Generated by scripts/generate-gdscript-catalog.mjs. Edit the C# catalog or generator.
extends RefCounted
## Reusable definitions for known properties and callback values.
##
## Helpers configure definitions; [method Tweens.play] starts playback.
## Arguments follow the C# definition constructors: endpoint, duration, easing, delay.

## Timing and mode constants shared by every definition.
const CatalogTypes = preload("types.gd")
const CompoundAdapter = preload("compound_adapter.gd")
`;
for (const e of entries) {
  const p = e.kind === 'property' ? e.paths[0] : '';
  const named = `TweensGdDefinition.named(^"${p}", &"${e.target}", TYPE_${types[e.type]}, to, seconds, easing, delay)`;
  gd += `\n## Creates a reusable ${e.csharp} definition for [${e.target}].\n`;
  const endpoint = e.type === 'double' || e.type === 'float' ? '[float]' : `[${e.type}]`;
  const shorthand = ['Vector2', 'Vector3', 'Vector4', 'Color'].includes(e.type)
    ? ' or a numeric component [Array]'
    : '';
  gd += `## [param to] accepts ${endpoint}${shorthand}; [code]null[/code] uses the value captured at start, before the delay.\n`;
  gd += `## Duration and delay are in seconds. C# equivalent: [code]new Tweens.${e.csharp}(to, duration, ease, delay)[/code].\n`;
  gd += `static func ${e.name}(to: Variant = null, seconds: float = 0.0, easing: int = CatalogTypes.Ease.LINEAR,\n`;
  gd += `\t\tdelay: float = 0.0) -> TweensGdDefinition:\n`;
  if (e.kind === 'property') {
    gd += `\treturn ${named}\n`;
    continue;
  }
  gd += `\tvar definition := ${named}\n`;
  if (e.kind === 'value') gd += `\tdefinition.initial_value = ${defaults[e.type]}\n`;
  if (['compound', 'global_quaternion'].includes(e.kind)) {
    gd += '\tvar adapter := CompoundAdapter.new()\n';
    gd +=
      e.kind === 'compound'
        ? `\tadapter.paths = [${e.paths.map((p) => `^"${p}"`).join(', ')}]\n`
        : '\tadapter.global_quaternion = true\n';
    gd += '\tdefinition.adapter = adapter\n';
  }
  gd += '\treturn definition\n';
}
let md =
  '# GDScript helper catalog\n\nEach helper returns a reusable definition:\n`Tweens.position_2d(destination, seconds, In.SINE | Out.CUBIC)`. All helpers accept\n`(to = null, seconds = 0.0, easing = Tweens.Ease.LINEAR, delay = 0.0)`; null captures the current value.\nNative target and value types are checked at activation.\n\n';
md +=
  'Property is the path each helper tweens. Compound helpers write several properties together, and\n';
md += 'callback-value helpers write none.\n\n';
// The path a helper writes: its definition's property, or its compound adapter's paths.
const property = (e) =>
  e.kind === 'property'
    ? `\`${e.paths[0]}\``
    : e.kind === 'compound'
      ? e.paths.map((p) => `\`${p}\``).join(', ')
      : e.kind === 'global_quaternion'
        ? '`global_rotation`'
        : '';
md += '| Helper | Property | Target | Value |\n| --- | --- | --- | --- |\n';
for (const e of entries)
  md += `| \`${e.name}\` | ${property(e)} | ${e.target} | ${e.type === 'double' ? 'float' : e.type} |\n`;
for (const [file, content] of [
  ['addons/tweens_gd/catalog.gd', gd],
  ['addons/tweens_gd/CATALOG.md', md],
  ['tests/conformance/adapters.json', JSON.stringify(entries, null, 2) + '\n'],
]) {
  const filename = path.join(root, file);
  if (check) {
    if (
      !fs.existsSync(filename) ||
      fs.readFileSync(filename, 'utf8').replaceAll('\r\n', '\n') !== content
    )
      throw new Error(
        `Stale generated file: ${file}. Run node scripts/generate-gdscript-catalog.mjs`,
      );
  } else fs.writeFileSync(filename, content);
}
console.log(`${check ? 'Verified' : 'Generated'} ${entries.length} GDScript helpers.`);
